const assert=require("node:assert/strict");
const O=require("../operations/core.js");
const a=O.makeAsset({topicId:"topic-1",title:"sample"});
assert.equal(a.phase,"draft");
assert.equal(O.stableId("topic-1"),"article_topic-1");
assert.throws(()=>O.transition(a,"published",{}),/INVALID_TRANSITION/);
assert.throws(()=>O.transition(a,"approved",{}),/APPROVAL_REQUIRED/);
const approved=O.transition(a,"approved",{explicitApproval:true,approvedBy:"owner",packageId:"pkg1"});
assert.equal(approved.phase,"approved");
assert.throws(()=>O.transition(approved,"in_wechat_draft",{}),/DRAFT_RECEIPT_REQUIRED/);
const draft=O.transition(approved,"in_wechat_draft",{draftReceipt:"receipt",qaPassed:true});
assert.throws(()=>O.transition(draft,"published",{permanentUrl:"https://mp.weixin.qq.com/s/abc"}),/PUBLISH_EVIDENCE_REQUIRED/);
const published=O.transition(draft,"published",{permanentUrl:"https://mp.weixin.qq.com/s/abc",explicitPublishAuthorization:true,previewPassed:true,backendVerified:true});
assert.equal(published.phase,"published");
let tasks=O.upsertTask([],{assetId:a.id,platform:"wechat",status:"planned"});
tasks=O.upsertTask(tasks,{assetId:a.id,platform:"wechat",status:"planned"});
assert.equal(tasks.length,1);
tasks=O.upsertTask(tasks,{assetId:a.id,platform:"wechat",status:"awaiting_user"});
assert.equal(tasks.length,1);
assert.throws(()=>O.upsertTask(tasks,{assetId:a.id,platform:"wechat",status:"published"}),/TASK_PUBLISH_PROOF_REQUIRED/);
tasks=O.upsertTask(tasks,{assetId:a.id,platform:"wechat",status:"published",permanentUrl:"https://mp.weixin.qq.com/s/abc",backendVerified:true,explicitPublishAuthorization:true});
assert.throws(()=>O.upsertTask(tasks,{assetId:a.id,platform:"wechat",status:"planned"}),/LOCKED_TASK/);
const m1=O.metric({assetId:a.id,platform:"wechat",day:"2026-11-08",views:120});
const m2=O.metric({assetId:"article_topic-2",platform:"wechat",day:"2026-11-04",views:80});
const dates={[a.id]:"2026-11-01","article_topic-2":"2026-10-28"};
let review=O.sameAge([m1,m2],a.id,"article_topic-2",7,dates);
assert.equal(review.ratio,1.5);
review=O.sameAge([m1],a.id,"article_topic-2",7,dates);
assert.equal(review.ratio,null);assert.equal(review.previous.value,null);
assert.throws(()=>O.metric({assetId:a.id,platform:"wechat",day:"2026-11-08",views:-1}),/INVALID_METRIC/);
assert.match(O.utm({campaign:a.id}),/utm_campaign=article_topic-1/);
assert.equal(O.parseAttribution("?utm_source=wechat&utm_medium=article&utm_campaign=article_topic-1").campaign,a.id);
assert.equal(O.parseAttribution("?utm_campaign=%3Cscript%3E"),null);
