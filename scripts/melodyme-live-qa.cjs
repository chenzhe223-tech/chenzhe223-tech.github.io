const { chromium } = require('playwright');
const fs = require('fs');
const path = require('path');
const target = process.env.MELODYME_URL || 'https://chenzhe223-tech.github.io/melodyme/';
const out = 'melodyme-live-results';
fs.mkdirSync(out, {recursive:true});
const results=[];
function record(name,ok,detail=''){results.push({name,status:ok?'PASS':'FAIL',detail:String(detail)});console.log('['+(ok?'PASS':'FAIL')+'] '+name+(detail?' — '+detail:''));}
(async()=>{
 let browser;
 try{
  browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1280,height:900}});
  await page.addInitScript(()=>{if(!sessionStorage.getItem('melodyme-test-clean')){localStorage.clear();sessionStorage.setItem('melodyme-test-clean','1')}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const response=await page.goto(target,{waitUntil:'domcontentloaded',timeout:45000});
  record('Production route responds',!!response&&response.status()===200,'HTTP '+(response&&response.status()));
  record('Product title', (await page.title()).includes('MelodyMe'), await page.title());
  await page.getByRole('button',{name:/开始探索/}).click();
  await page.locator('#next').click();
  record('Empty story feedback',await page.locator('#feedback').innerText().then(t=>t.length>0),'Empty input receives guidance');
  await page.locator('#story').fill('傍晚走在海边，听到一首歌，突然想起毕业那天的告别。');
  await page.locator('#next').click();
  await page.locator('[data-mood="怀念"]').click();
  await page.locator('#next').click();
  await page.locator('#songinput').fill('线上验收测试歌曲');
  await page.locator('#artistinput').fill('MelodyMe QA');
  await page.locator('#next').click();
  await page.locator('[data-style="电影雾光"]').click();
  await page.locator('#next').click();
  await page.locator('#results').waitFor({state:'visible',timeout:5000});
  record('Twelve poster styles',await page.locator('.stylepick').count()===12,'12 distinct style options');
  await page.locator('#autoStyle').click();
  record('Local style recommendation is selectable',await page.locator('.stylepick[aria-pressed="true"]').count()===1,'Recommendation remains user-overridable');
  record('Real music card and Shazam URL input',await page.locator('#musiccard').count()===1&&await page.locator('#shazamUrl').count()===1,'Music card renders without inventing a track');
  await page.locator('#shazamUrl').fill('https://www.shazam.com/song/123456789/example-song');
  await page.locator('#applyShazam').click();
  record('Shazam URL action',await page.locator('#shazamLink').getAttribute('href')==='https://www.shazam.com/song/123456789/example-song','Specific official song URL is reflected in the music card');
  record('Map journey to artwork',await page.locator('#postertitle').innerText().then(t=>t.length>0),'Memory → mood → optional song clue → artwork');
  await page.locator('#storycopy').fill('Live QA edited story');
  await page.locator('#sharecopy').fill('Live QA share copy');
  await page.locator('#save').click();
  await page.getByRole('button',{name:/我的作品/}).click();
  await page.locator('#saved strong').waitFor({timeout:3000});
  await page.reload({waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:/我的作品/}).click();
  await page.locator('#saved strong').waitFor({timeout:3000});
  record('Local work persistence after reload',true,'Saved item restored from browser storage');
  await page.screenshot({path:path.join(out,'desktop.png'),fullPage:true});
  record('Desktop JavaScript errors',errors.length===0,errors.join('; ')||'none');
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});
  const mobileErrors=[];mobile.on('pageerror',e=>mobileErrors.push(e.message));
  const mr=await mobile.goto(target,{waitUntil:'domcontentloaded',timeout:45000});
  const dims=await mobile.evaluate(()=>({viewport:document.documentElement.clientWidth,document:document.documentElement.scrollWidth}));
  record('Mobile route and overflow',!!mr&&mr.status()===200&&dims.document<=dims.viewport+2,JSON.stringify({status:mr&&mr.status(),...dims}));
  await mobile.getByRole('button',{name:/开始探索/}).click();
  await mobile.locator('#story').fill('手机端验收：一首歌让我想起一次旅行。');
  await mobile.locator('#next').click();
  await mobile.locator('[data-mood="自由"]').click();
  await mobile.locator('#next').click();
  await mobile.locator('#next').click();
  await mobile.locator('#next').click();
  await mobile.locator('#results').waitFor({state:'visible',timeout:5000});
  record('Mobile map journey',true,'One-sentence input → choices → artwork');
  record('Mobile JavaScript errors',mobileErrors.length===0,mobileErrors.join('; ')||'none');
  await mobile.screenshot({path:path.join(out,'mobile.png'),fullPage:true});
  const downloadPromise=mobile.waitForEvent('download',{timeout:5000});
  await mobile.locator('#download').click();
  const download=await downloadPromise;
  record('SVG poster export',download.suggestedFilename().endsWith('.svg'),download.suggestedFilename());
  await mobile.close();
 }catch(e){record('Test runner exception',false,e.stack||e.message||e)}
 finally{if(browser)await browser.close().catch(()=>{})}
 const failed=results.filter(r=>r.status==='FAIL');
 fs.writeFileSync(path.join(out,'report.json'),JSON.stringify({target,finishedAt:new Date().toISOString(),summary:{passed:results.length-failed.length,failed:failed.length},results},null,2));
 if(failed.length)process.exitCode=1;
})();
