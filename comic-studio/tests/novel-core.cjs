'use strict';
const assert=require('node:assert/strict');
const crypto=require('node:crypto');
if(!globalThis.crypto)globalThis.crypto=crypto.webcrypto;
const core=require('../novel-core.js');
const fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const source=fs.readFileSync(path.resolve(__dirname,'../creative-director.js'),'utf8');
const start=source.indexOf('function digest('),end=source.indexOf('function checks(',start);
assert.ok(start>0&&end>start,'creative director lock must remain auditable');
const cx={clean:x=>String(x||'').trim(),payload:p=>p.payload||{}};
vm.runInNewContext(source.slice(start,end)+'\nthis.hashNovel=digest;',cx);
const before={title:'原创故事',sourceTitle:'文字来源',payload:{chapters:2}};
const base=cx.hashNovel(before);
assert.equal(base,cx.hashNovel({...before,novelSkill:null}),'non-novel approval locks must preserve their historical identity');
const withNovel={...before,novelSkill:{provenance:{sha256:'a'.repeat(64)},rights:{mode:'literary_review'}}};
const yes=cx.hashNovel(withNovel);
assert.notEqual(base,yes,'source-index identity must be included in creator approval');
assert.notEqual(yes,cx.hashNovel({...withNovel,novelSkill:{...withNovel.novelSkill,provenance:{sha256:'b'.repeat(64)}}}),'different novel file invalidates approval');
assert.notEqual(yes,cx.hashNovel({...withNovel,novelSkill:{...withNovel.novelSkill,rights:{mode:'faithful'}}}),'rights changes invalidate approval');

(async()=>{
 const chapters=[1,2,3,4].map(i=>'第'+i+'章 '+['开始','冲突','抉择','终局'][i-1]+'\n'+('母亲和孩子在森林里的故事，孤独与希望交织。后来，人物面对自由与家庭的选择。\n').repeat(15)).join('\n\n');
 assert.ok(chapters.length>450);
 const all=core.chapterize([{text:chapters,location:'UTF-8 原稿'}]);
 assert.equal(all.length,4,'explicit chapter boundaries preserved');
 assert.ok(all.every(x=>x.synthetic===false),'recognized headings are genuine chapter boundaries');
 assert.ok(all.reduce((n,x)=>n+x.text.length,0)>chapters.length-100,'full novel not silently truncated');
 const sha='a'.repeat(64),skill=core.buildSkill(all,{fileName:'原创故事.txt',fileType:'txt',sha256:sha});
 assert.equal(skill.schema,'davylab.worldtoon.novel-skill.v1');
 assert.equal(skill.provenance.sha256,sha);
 assert.equal(skill.provenance.chapter_count,4);
 assert.equal(skill.distillation.semantic_status,'not_performed','lexical hints must not pretend model understanding');
 assert.equal(skill.qa.ready_for_publication,false);
 assert.equal(skill.qa.interpretation_not_yet_generated,true);
 assert.ok(skill.themes.some(t=>t.name==='家庭与代际'));
 assert.ok(skill.chapter_index.every(x=>x.locator&&x.chapter_id),'every chapter has traceable source locator');
 assert.ok(!JSON.stringify(skill).includes('母亲和孩子在森林里的故事'),'do not persist full passages as synopsis');
 assert.equal(skill.three_axes.length,3);
 const fake={name:'original.txt',size:Buffer.byteLength(chapters),arrayBuffer:async()=>Uint8Array.from(Buffer.from(chapters)).buffer};
 const extracted=await core.extractFile(fake);
 assert.equal(extracted.sha256,crypto.createHash('sha256').update(chapters).digest('hex'));
 assert.equal(extracted.chapters.length,4);
 assert.equal(extracted.chapters.map(x=>x.text.length).reduce((x,y)=>x+y,0)>chapters.length-100,true);
 await assert.rejects(()=>core.extractFile({name:'malware.exe',size:500,arrayBuffer:fake.arrayBuffer}),/仅支持/);
 assert.throws(()=>core.chapterize([{text:'假的长篇'.repeat(30)}]),/正文不足/);
 const plain='没有标题的长篇。\n\n'+('人生需要证据，也需要耐心。'.repeat(45)+'\n\n').repeat(32);
 const broken=core.chapterize([{text:plain,location:'第1卷'}]);
 assert.ok(broken.length>1);
 assert.ok(broken.every(x=>x.synthetic));
 assert.ok(broken.reduce((n,x)=>n+x.text.length,0)>plain.length-200,'fallback synthetic chunks preserve body');
 const excess='第1章\n'+('今天是个好日子'.repeat(10)).repeat(60000);
 assert.throws(()=>core.chapterize([{text:excess,location:'big'}]),/超过400万字符/);
 console.log('NOVEL CORE PASS: 4 real chapters, no truncation, source SHA, false-semantic guard, fallback indexing and file limits');
})().catch(e=>{console.error(e);process.exitCode=1});
