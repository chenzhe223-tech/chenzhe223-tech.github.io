import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const withoutExport = s => s.replace(/^export (const|async function|function) /gm, '$1 ');
const orbit = withoutExport(read('src/orbit.js'));
const globe = withoutExport(read('src/globe.js'));
const page = withoutExport(read('src/page.js')).replace(/^import .*;\s*$/gm, '');
const brand = withoutExport(read('src/brand.js'));
const nobel = withoutExport(read('src/nobel.js'));
const curated = withoutExport(read('src/curated.js'));
const explore = withoutExport(read('src/explore.js'));
const discover = withoutExport(read('src/discover.js'));
const quota = withoutExport(read('src/quota.js'));
const quotaDO = read('src/quota-do.js');
const main = read('src/index.js').replace(/^import .*;\s*$/gm, '');
mkdirSync(new URL('../dist/', import.meta.url), { recursive: true });
writeFileSync(new URL('../dist/worker.js', import.meta.url), `${globe}\n${orbit}\n${brand}\n${page}\n${nobel}\n${curated}\n${explore}\n${discover}\n${quota}\n${quotaDO}\n${main}`);
console.log('Generated dist/worker.js from tested source modules');
